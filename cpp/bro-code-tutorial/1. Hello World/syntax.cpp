#include <iostream> //header file that contains functions for basic input and output operation

int main(){
    std::cout << "First Line" << '\n';
    std::cout << "Second Line"<< std::endl;
    return 0;

}


// std      = standard
// ::       = scope resolution operator
// cout     = console output
// cin      = console input

// endl     = end line like Enter   : flushing
// '\n'     = like end line         : no flushing
// ;        = this line complete

// return   = return value to main()
// 0        = success

// <<       = output operator or insertion operator
// >>       = input operator or extraction operator

// //       = for line comment
// /* */    = for open space comment 