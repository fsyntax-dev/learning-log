

//declaration - tells complier it exist

// initialization - giving variable its first value when its created

int main(){

    //variable declaration
    int x;

    //variable assignment
    x = 5;
    // declare first assign later

 
    //variable initialization
    int y = 5;
    // immediate declare and assign

    int a = 5;  // copy initialization
    int b (6);  // direct initialization

    
    int c {7};  // list initialization  // uniform initialization  // brace initialization 
                // disallow narrowing conversion

    int d {};   // zero initialization
                // good because the variable default as 0 not as garbage value            
    return 0;
}


