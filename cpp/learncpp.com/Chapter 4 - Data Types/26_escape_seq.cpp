#include <iostream>

int main(){

    //escape sequence
    // \n - new line
    // \t - tab
    // \" - quote

    std::cout << "This is the first sentence\n";
    std::cout << "This is the second sentence\n";
    std::cout << "This is part one\t This part two\n";

    std::cout << " \"Quote Text\" \n";

    return 0;
}